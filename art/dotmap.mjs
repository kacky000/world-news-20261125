function inside(lon, lat, ring) {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export const isLand = (lon, lat) => LAND.some((r) => inside(lon, lat, r));

// Equirectangular frame from lat 76 to -48, lon -170 to 190.
export function projector(x, y, w, h) {
  const LON0 = -170, LON1 = 190, LAT0 = 76, LAT1 = -48;
  return (lon, lat) => {
    const L = lon < LON0 ? lon + 360 : lon;
    return [x + ((L - LON0) / (LON1 - LON0)) * w, y + ((LAT0 - lat) / (LAT0 - LAT1)) * h];
  };
}

// pins: [{n, lat, lon, color}]
export function dotMap(x, y, w, h, pins, o = {}) {
  const { step = 5, dot = 1.55, land = 'var(--land)', bg = 'var(--sea)' } = o;
  const P = projector(x, y, w, h);
  const out = [rect(x, y, w, h, { fill: bg, rx: 4 })];
  for (let py = y + step / 2; py < y + h; py += step) {
    for (let px = x + step / 2; px < x + w; px += step) {
      const lon = -170 + ((px - x) / w) * 360;
      const lat = 76 - ((py - y) / h) * 124;
      const L = lon > 180 ? lon - 360 : lon;
      if (isLand(L, lat)) out.push(circle(px.toFixed(1), py.toFixed(1), dot, { fill: land }));
    }
  }
  // pins sorted south-to-north so northern labels sit on top
  const sorted = [...pins].sort((a, b) => a.lat - b.lat);
  const placed = [];
  for (const p of sorted) {
    let [cx, cy] = P(p.lon, p.lat);
    // nudge pins that would sit on top of an earlier one
    while (placed.some(([px, py]) => Math.hypot(px - cx, py - cy) < 13)) cx += 13;
    placed.push([cx, cy]);
    out.push(
      g(
        {},
        circle(cx, cy, 7.2, { fill: p.color, stroke: 'var(--paper)', stroke_width: 1.4 }),
        text(cx, cy + 3.4, p.n, { size: 9, weight: 700, fill: '#fff', anchor: 'middle', kind: 'headc' }),
      ),
    );
  }
  return g({}, out);
}
